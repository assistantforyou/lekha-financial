#!/usr/bin/env node
/* Builds the unified LEKHA app's classic-engine inputs from the generated V3 build (which itself is generated from V2):
     public/app/classic.css       V3 base + V3 feature CSS, adapted to live inside the new shell (body -> .cx, shell-only rules dropped)
     public/app/lekha-ui.js       V3 UI script, default theme switched to LEKHA Teal
     public/app/lekha-themes.js   V3 themes + LEKHA Teal / LEKHA Teal Light
     app/stage.html               every classic panel (pane) extracted from public/v3/index.html, injected into the app page by vite
   Run `node scripts/build-v3.mjs` first if V2 changed. Every edit is a named patch that must match exactly once, so drift fails loudly. */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const P = (...a) => join(ROOT, ...a);
const rd = (...a) => readFileSync(P(...a), "utf8");
function patch(s, find, repl, name) {
  const n = s.split(find).length - 1;
  if (n !== 1) throw new Error(`patch "${name}" matched ${n} times (expected 1)`);
  return s.replace(find, () => repl);
}
mkdirSync(P("public/app"), { recursive: true });
const HDR = (what) => `/* GENERATED by scripts/build-app.mjs from ${what}. Do not edit; change the patch in the build script. */\n`;

/* ---------- CSS ---------- */
let css = rd("public/v3/lekha-base.css") + "\n" + rd("public/v3/lekha-v3.css");
css = css.replace(/\/\* GENERATED[^\n]*\*\/\n/g, "");
css = css.replace(/body::before\{[^}]*\}/g, "");
css = css.replace(/(^|\n)body\{/g, "$1.cx{");
css = css.replace(/html\.embed[^{}]*\{[^}]*\}/g, "");
writeFileSync(P("public/app/classic.css"), HDR("public/v3/lekha-base.css + lekha-v3.css") + css);

/* ---------- UI script: default theme = LEKHA Teal ---------- */
let ui = rd("public/v3/lekha-ui.js");
ui = ui.replace(/\/\* GENERATED[^\n]*\*\/\n/, "");
ui = patch(ui, `{ theme: LS("v3.theme") || "lekha-navy" }`, `{ theme: LS("v3.theme") || "lekha-teal" }`, "default theme");
writeFileSync(P("public/app/lekha-ui.js"), HDR("public/v3/lekha-ui.js") + ui);

/* ---------- themes: add LEKHA Teal (main's palette) next to LEKHA Navy ---------- */
let th = rd("public/v3/lekha-themes.js");
th = th.replace(/\/\* GENERATED[^\n]*\*\/\n/, "");
th = patch(th, `    ["lekha-navy", "LEKHA Navy", "d",`,
  `    ["lekha-teal", "LEKHA Teal", "d", "0B0E11 13181D EDF0F3 98A2AD 3DCDAA FF6F63 F0A33A E8C66A 3FD18D 5FB3C9 7FA7E0 A893D9"],\n    ["lekha-navy", "LEKHA Navy", "d",`, "teal dark");
th = patch(th, `    ["lekha-light", "LEKHA Light", "l",`,
  `    ["lekha-teal-light", "LEKHA Teal Light", "l", "F3F1EA FFFFFF 14171C 656C76 0A7A6A C63A2F A96300 A96300 0F8050 0A7A6A 2C5AA0 7A4FB5"],\n    ["lekha-light", "LEKHA Light", "l",`, "teal light");
writeFileSync(P("public/app/lekha-themes.js"), HDR("public/v3/lekha-themes.js") + th);

/* ---------- stage: every pane of the generated V3 page, with ids intact ---------- */
const html = rd("public/v3/index.html");
function balanced(src, start) {                       // src[start] === "<" of an opening <div ...>; returns end index (exclusive) of the matching </div>
  const re = /<div\b|<\/div>/g; re.lastIndex = start; let depth = 0, m;
  while ((m = re.exec(src))) { if (m[0] === "</div>") { if (--depth === 0) return m.index + 6; } else depth++; }
  throw new Error("unbalanced div at " + start);
}
const panes = []; let at = 0, m;
const open = /<div class="v3pane[^"]*" id="(tab-[a-z-]+)"[^>]*>/g;
while ((m = open.exec(html))) {
  const end = balanced(html, m.index); const inner = html.slice(m.index + m[0].length, end - 6);
  const cls = /tabpane/.test(m[0]) ? "tabpane" : "";
  panes.push({ id: m[1], cls, inner });
  open.lastIndex = end;
}
const want = ["tab-pf-overview", "tab-pf-holdings", "tab-pf-risk", "tab-sim", "tab-mac-regime", "tab-mac-rotation", "tab-mac-intel", "tab-mac-appetite", "tab-val", "tab-an-deep", "tab-an-council", "tab-an-reports", "tab-sec-now", "tab-sec-rrg", "tab-sec-lead", "tab-sec-breadth"];
for (const w of want) if (!panes.some((p) => p.id === w)) throw new Error("pane missing in v3 index: " + w);
if (panes.length !== want.length) throw new Error("unexpected panes: " + panes.map((p) => p.id).join(","));
const footer = (/<footer>[\s\S]*?<\/footer>/.exec(html) || [""])[0];
/* V2's Projection Lab panel (V3 replaced it with the simulation; the lab is still part of V2, so it gets its own pane) */
const v2 = rd("public/v2/index.html");
const pj = /<section class="panel" id="proj-panel"[\s\S]*?<\/section>/.exec(v2);
if (!pj) throw new Error("proj-panel not found in v2");
const projPane = { id: "tab-sim-proj", cls: "", inner: pj[0].replace(' style="display:none"', "") };
const stage = [...panes, projPane].map((p) => `<div class="${p.cls}" id="${p.id}" hidden>${p.inner}</div>`).join("\n") + '\n<div class="tabpane" id="tab-set" hidden></div>\n' + footer.replace("<footer>", '<footer id="app-foot">');
writeFileSync(P("app/stage.html"), "<!-- GENERATED by scripts/build-app.mjs from public/v3/index.html + public/v2/index.html -->\n" + stage);
/* the projection lab fetches this by a relative URL; serve it at the site root */
import { copyFileSync } from "node:fs";
copyFileSync(P("public/v2/pt-projection-data.json"), P("public/pt-projection-data.json"));
console.log("build-app: " + panes.length + " panes + projection, css " + css.length + "B");
