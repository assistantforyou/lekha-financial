#!/usr/bin/env node
// Builds the per-language dictionaries (public/i18n/<code>.js) from the English master list and the
// translation parts. Usage: node scripts/build-i18n.mjs [--check]
//   scripts/i18n/master.json   English keys in dictionary form ({1} = a number/date/ticker, <1>…</1> = inline markup)
//   scripts/i18n/parts/*.json  { "<index in master>": [th, zh-Hans, ja, ko, es, hi, vi, fr], ... }
//   scripts/i18n/zh-hant.json  { "chars": { "简": "簡", ... }, "phrases": [["软件","軟體"], ...] }  (zh-Hans -> zh-Hant)
// Every translation is checked: it must contain the same {n} placeholders and <n> tags as its source.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "scripts", "i18n"), out = path.join(root, "public", "i18n");
const check = process.argv.includes("--check");
const LANGS = ["th", "zh-Hans", "ja", "ko", "es", "hi", "vi", "fr"];
const master = JSON.parse(fs.readFileSync(path.join(dir, "master.json"), "utf8"));
const partsDir = path.join(dir, "parts");
const parts = fs.readdirSync(partsDir).filter((f) => f.endsWith(".json") && !f.startsWith(".")).sort();
const rows = {};
for (const f of parts) Object.assign(rows, JSON.parse(fs.readFileSync(path.join(partsDir, f), "utf8")));

const sig = (s) => (s.match(/\{\d+\}|<\/?\d+\/?>/g) || []).sort().join(" ");
const problems = [], dicts = Object.fromEntries(LANGS.map((l) => [l, {}]));
for (const [idx, arr] of Object.entries(rows)) {
  // a row is keyed by its index in master.json, or by "@<English key>" for extra phrases (list items, fragments)
  const key = idx[0] === "@" ? idx.slice(1) : master[+idx];
  if (key == null) { problems.push(`#${idx}: no such master entry`); continue; }
  if (arr.length !== LANGS.length) { problems.push(`#${idx}: expected ${LANGS.length} translations, got ${arr.length}`); continue; }
  LANGS.forEach((l, i) => {
    const v = arr[i];
    if (!v) return;
    // a translation may drop a placeholder (e.g. a redundant "{1}"), but never invent one or break tag pairs
    const src = new Set(key.match(/\{\d+\}|<\/?\d+\/?>/g) || []), got = v.match(/\{\d+\}|<\/?\d+\/?>/g) || [];
    const bad = got.filter((t) => !src.has(t));
    const tagsSrc = (key.match(/<\/?\d+\/?>/g) || []).sort().join(""), tagsGot = got.filter((t) => t[0] === "<").sort().join("");
    if (bad.length || tagsSrc !== tagsGot) { problems.push(`#${idx} [${l}] placeholders/tags differ: ${sig(key)}  ->  ${sig(v)}`); return; }
    dicts[l][key] = v;
  });
}
// Simplified -> Traditional
const hantFile = path.join(dir, "zh-hant.json");
if (fs.existsSync(hantFile)) {
  const H = JSON.parse(fs.readFileSync(hantFile, "utf8")), chars = H.chars || {}, phrases = (H.phrases || []).sort((a, b) => b[0].length - a[0].length);
  const conv = (s) => { for (const [a, b] of phrases) s = s.split(a).join(b); return Array.from(s).map((c) => chars[c] || c).join(""); };
  dicts["zh-Hant"] = Object.fromEntries(Object.entries(dicts["zh-Hans"]).map(([k, v]) => [k, conv(v)]));
}
// glossary terms become slots at match time: each needs its own dictionary row in every language
const gloss = JSON.parse(fs.readFileSync(path.join(dir, "glossary.json"), "utf8"));
for (const l of Object.keys(dicts)) {
  const gaps = gloss.filter((t) => dicts[l][t] == null);
  if (gaps.length) console.warn(`[${l}] glossary terms without a translation: ${gaps.join(", ")}`);
}
const missing = {};
for (const l of Object.keys(dicts)) missing[l] = master.length - Object.keys(dicts[l]).length;
console.log("master entries:", master.length, "(+" + Object.keys(rows).filter((k) => k[0] === "@").length + " extras)", "| parts:", parts.length, "| translated rows:", Object.keys(rows).length);
console.log("per language (translated / master):", Object.keys(dicts).map((l) => `${l} ${Object.keys(dicts[l]).length}`).join("  "));
if (problems.length) { console.error(problems.join("\n")); console.error(`\n${problems.length} problem(s)`); }
if (check) process.exit(problems.length ? 1 : 0);
fs.mkdirSync(out, { recursive: true });
for (const [l, d] of Object.entries(dicts)) {
  const sorted = Object.fromEntries(Object.entries(d));
  fs.writeFileSync(path.join(out, l + ".js"), "/* generated by scripts/build-i18n.mjs: do not edit */\nwindow.PT_GLOSS=" + JSON.stringify(gloss) + ";\nwindow.PT_DICT=" + JSON.stringify(sorted) + ";\n");
}
console.log("wrote", Object.keys(dicts).length, "dictionaries to public/i18n/");
process.exit(problems.length ? 1 : 0);
